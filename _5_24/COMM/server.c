/******************************************************************************
 * server.c — 共享内存通信示例：服务端（读者）
 *
 * 功能：
 *   1. 创建共享内存段（createShm）
 *   2. 将共享内存挂接到进程地址空间（shmat）
 *   3. 循环读取共享内存内容并打印
 *   4. 卸载共享内存（shmdt）并删除共享内存段（destroyShm）
 *
 * 运行时序：
 *   先启动 server，再启动 client。
 *   server 创建共享内存后进入读取循环，
 *   同时 client 会向同一块内存写入字符，
 *   server 能看到内容实时变化。
 *
 * 编译 & 运行：
 *   $ make
 *   $ ./server &    # 后台运行 server
 *   $ ./client      # 前台运行 client
 *
 * 注意：
 *   共享内存本身不提供任何同步/互斥机制。
 *   此示例仅用于演示基本用法，实际项目中需要配合信号量等同步手段。
 ******************************************************************************/

#include "comm.h"    /* createShm, getShm, destroyShm */
#include <unistd.h>  /* sleep() */

int main(void)
{
    /*
     * 第 1 步：创建共享内存
     *   大小设为 4096 字节（恰好是 x86 常见页大小 4KB）。
     *   共享内存大小最好按页对齐（getpagesize() 的整数倍），
     *   这样更符合内核内存管理习惯，减少碎片。
     */
    int shmid = createShm(4096);

    /*
     * 第 2 步：挂接（attach）共享内存到当前进程的地址空间
     *   shmat(shmid, NULL, 0)
     *     第 1 参: shmid — 共享内存标识符
     *     第 2 参: NULL — 让内核自动选择挂接地址
     *     第 3 参: 0    — 可读写模式（SHM_RDONLY 表示只读）
     *   返回值: 共享内存段在当前进程中的起始地址
     *
     *   挂接后，addr 指针就可以像普通 malloc 出来的内存一样使用。
     */
    char *addr = shmat(shmid, NULL, 0);

    /*
     * 短暂休眠 2 秒，等待 client 进程启动并挂接。
     * （实际项目中应用信号量或其它同步机制替代这种粗糙的 sleep）
     */
    sleep(2);

    /*
     * 第 3 步：循环读取共享内存中的内容
     *   client 会从 'A' 开始依次写入字符，写满 26 个字母。
     *   server 每秒打印一次当前共享内存的内容。
     *
     *   你能观察到输出从 "A" 逐步增长到 "ABCDEFGHIJKLMNOPQRSTUVWXYZ"：
     *   - 每次 client 写入新字符后追加一个 '\0' 作为字符串结尾，
     *     所以 printf("%s") 能正常打印。
     *
     *   注意并发问题：
     *   server 在 printf 时，client 可能正在写入——
     *   没有任何锁保护，你可能看到不完整或乱序的内容。
     *   这是共享内存的固有缺陷，必须配合信号量等同步机制。
     */
    int i = 0;
    while (i++ < 26) {
        printf("client# %s\n", addr);
        sleep(1);
    }

    /*
     * 第 4 步：卸载（detach）共享内存
     *   shmdt() 将共享内存段从当前进程的地址空间中移除。
     *   之后 addr 指针不再有效，继续使用会导致段错误。
     */
    shmdt(addr);

    /*
     * 稍微等一下 client，确保它也卸载了之后再删除。
     */
    sleep(2);

    /*
     * 第 5 步：删除共享内存段
     *   只有负责创建的进程才应该调用 destroyShm()。
     *   内核会等所有进程都 shmdt() 之后才真正释放物理内存。
     */
    destroyShm(shmid);

    return 0;
}
