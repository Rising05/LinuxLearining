/******************************************************************************
 * ShmServer.cc — 共享内存通信示例：服务端（读端）
 *
 * ── 角色定位 ──────────────────────────────────────────────────────────────
 *
 *   本程序作为共享内存通信的「消费者」：
 *     - 负责创建共享内存段（所有者身份）
 *     - 阻塞等待 client 发来的通知（通过 FIFO）
 *     - 收到通知后读取共享内存内容并打印到终端
 *     - 收到 "quit" 时退出循环，清理所有资源
 *
 * ── 运行方式 ──────────────────────────────────────────────────────────────
 *
 *   ./shm_server                  # 启动后阻塞，等待 client 连接
 *   （另一个终端）./shm_client     # 输入文字，server 会输出
 *
 *   输入 "quit" 两端同时退出。
 *
 * ── 共享内存生命周期 ─────────────────────────────────────────────────────
 *
 *   创建 → 挂接 → 使用 → 卸载 → 删除
 *   (shmget) (shmat)  (读写) (shmdt) (shmctl IPC_RMID)
 *
 *   注意：只有 server 负责创建和删除共享内存（IPC_CREAT | IPC_EXCL）。
 *        client 只获取已存在的共享内存，不参与创建/删除。
 ******************************************************************************/

#include "Comm.hpp"

/*
 * 全局 Init 对象：
 *   - 程序启动时，构造函数执行 mkfifo() 创建 FIFO 文件
 *   - 程序结束时，析构函数执行 unlink() 删除 FIFO 文件
 *   - 因为 server 和 client 都会编译链接 Comm.hpp，两边各自有一个 Init 对象。
 *     第一个启动的进程负责实际创建 FIFO，第二个启动时 mkfifo() 会失败
 *     （文件已存在），但这里没处理这个错误……实际项目中应改进。
 */
Init init;

int main()
{
    /**************************************************************************
     * 步骤 1：生成 IPC 键值
     *
     * ftok() 将路径名 + 项目 ID 合成为一个 System V IPC key。
     * server 和 client 必须使用相同的 PATH_NAME + PROJ_ID，
     * 否则会拿到不同的 key，无法通信。
     *
     * key_t 本质是一个整数，内核用它来索引 IPC 资源。
     **************************************************************************/
    key_t k = ftok(PATH_NAME, PROJ_ID);
    assert(k != -1);
    Log("create key done", Debug)
        << " server key : " << TransToHex(k) << endl;

    /**************************************************************************
     * 步骤 2：创建共享内存段
     *
     * shmget(key, size, flags) 参数说明：
     *   - k        : IPC 键值
     *   - SHM_SIZE : 4096 字节（4KB）
     *   - IPC_CREAT | IPC_EXCL | 0666 :
     *       · IPC_CREAT  — 如果不存在则创建
     *       · IPC_EXCL   — 如果已存在则报错（保证拿到的是新创建的段）
     *       · 0666       — 权限位，所有用户可读写
     *
     * 返回值 shmid 是共享内存段的标识符（非负整数），后续操作都通过它引用。
     **************************************************************************/
    int shmid = shmget(k, SHM_SIZE, IPC_CREAT | IPC_EXCL | 0666);
    if (shmid == -1) {
        perror("shmget");   // 打印系统错误信息
        exit(1);
    }
    Log("create shm done", Debug)
        << " shmid : " << shmid << endl;

    /**************************************************************************
     * 步骤 3：挂接共享内存到进程地址空间
     *
     * shmat(shmid, shmaddr, shmflg) 参数说明：
     *   - shmid    : 共享内存标识符
     *   - nullptr  : 让内核自动选择挂接地址
     *   - 0        : 默认 flag（可读写）
     *
     * 返回的指针指向共享内存在本进程地址空间中的映射位置，
     * 之后可以像普通堆内存一样直接读写这个指针指向的区域。
     * 多个进程各自 shmat 后，内核保证它们看到的是同一块物理内存。
     **************************************************************************/
    char* shmaddr = (char*)shmat(shmid, nullptr, 0);
    Log("attach shm done", Debug)
        << " shmid : " << shmid << endl;

    /**************************************************************************
     * 步骤 4：打开 FIFO 读端（阻塞直到 client 打开写端）
     *
     * 以 O_RDONLY 打开一个 FIFO 时，如果还没有进程以写方式打开同一个 FIFO，
     * open() 会阻塞。这保证了：
     *   - server 不会在 client 还没准备好时就尝试读取共享内存
     *   - 两边在 FIFO 打开的那一刻完成"握手"
     **************************************************************************/
    int fd = OpenFIFO(FIFO_NAME, READ);

    /**************************************************************************
     * 步骤 5：主循环 —— 等待通知 → 读取共享内存 → 打印
     *
     * 协议：
     *   - server 调用 Wait(fd) 阻塞，等待 client 的通知
     *   - client 向共享内存写完数据后调用 Signal(fd) 唤醒 server
     *   - server 被唤醒后读取共享内存内容（此时数据已就绪）并打印
     *   - 如果读到 "quit"，跳出循环
     *
     * 这个协议保证了：
     *   - server 不会在 client 写入一半时读取（原子性由协议保证）
     *   - server 不会被忙等浪费 CPU
     **************************************************************************/
    while (true) {
        Wait(fd);                                       // 阻塞等待 client 的通知
        printf("%s\n", shmaddr);                        // 输出共享内存中的内容
        if (strcmp(shmaddr, "quit") == 0)               // "quit" 是退出信号
            break;
    }

    /**************************************************************************
     * 步骤 6：清理资源（按创建的逆序）
     *
     * 1. 关闭 FIFO 文件描述符
     * 2. 卸载共享内存（shmdt）
     * 3. 删除共享内存段（shmctl + IPC_RMID）
     *    —— 注意：IPC_RMID 只是标记删除；内核会等所有进程都 shmdt 后才真正回收
     **************************************************************************/
    CloseFifo(fd);

    int n = shmdt(shmaddr);                             // 卸载共享内存
    assert(n != -1);
    (void)n;
    Log("detach shm done", Debug)
        << " shmid : " << shmid << endl;

    n = shmctl(shmid, IPC_RMID, nullptr);               // 标记删除共享内存段
    assert(n != -1);
    (void)n;
    Log("delete shm done", Debug)
        << " shmid : " << shmid << endl;

    return 0;
}
